"""Fundamental-domain representation of cells with full cubic (Oh, 3D) or square (D4, 2D) symmetry.

A cell of side 2*n_o voxels has mirror planes at its faces and mid-planes, and is invariant under axis
permutations. It is generated by its first octant (n_o)^d, mirrored across the mid-planes:

    full[i] = oct[i]              for i < n_o
    full[i] = oct[2 n_o - 1 - i]  for i >= n_o        (each axis)

The octant itself must be invariant under axis permutations, so its free entries are the index tuples
i <= j <= k (n_o (n_o+1) (n_o+2) / 6 in 3D). We store the whole octant array and keep it in the
permutation-symmetric subspace with `sym_perm`, which is the orthogonal projection onto that subspace in
the Euclidean inner product of the octant array. A standard normal on that subspace is sym_perm(white noise).
"""
import itertools
from math import comb

import jax.numpy as jnp
import numpy as np


def n_free(n_o, d=3):
    """Number of free parameters of a symmetric octant (n_o)^d."""
    return comb(n_o + d - 1, d)


def sym_perm(x, batch=0):
    """Average over all permutations of the last d axes (d = x.ndim - batch)."""
    d = x.ndim - batch
    lead = tuple(range(batch))
    perms = list(itertools.permutations(range(d)))
    out = 0
    for p in perms:
        out = out + jnp.transpose(x, lead + tuple(batch + q for q in p))
    return out / len(perms)


def mirror(oct_, batch=0):
    """Octant (..., n_o^d) -> full cell (..., (2 n_o)^d)."""
    x = oct_
    for ax in range(batch, x.ndim):
        x = jnp.concatenate([x, jnp.flip(x, ax)], axis=ax)
    return x


def fold(full, batch=0):
    """Full cell -> octant, averaging the 2^d mirror images (adjoint of `mirror` up to the factor 2^d)."""
    x = full
    for ax in range(batch, x.ndim):
        n = x.shape[ax] // 2
        a = jnp.take(x, jnp.arange(n), axis=ax)
        b = jnp.flip(jnp.take(x, jnp.arange(n, 2 * n), axis=ax), ax)
        x = 0.5 * (a + b)
    return x


def project_full(full, batch=0):
    """Orthogonal projection of a full-cell field onto the symmetric cells (returns the full cell)."""
    return mirror(sym_perm(fold(full, batch), batch), batch)


def exact_symmetrize(full):
    """Like project_full, but every orbit gets one value copied exactly (no round-off differences between
    symmetric voxels, so thresholds never split an orbit)."""
    oct_ = sym_perm(fold(full))
    n_o, d = oct_.shape[0], oct_.ndim
    return mirror(from_free(to_free(oct_), n_o, d))


def sym_residual(full):
    """Relative distance of a full cell from its symmetric projection, ||rho - P rho|| / ||rho||."""
    full = jnp.asarray(full)
    return float(jnp.linalg.norm(full - project_full(full)) / (jnp.linalg.norm(full) + 1e-300))


def free_index(n_o, d=3):
    """Index tuples of the free entries (sorted tuples)."""
    return np.array(list(itertools.combinations_with_replacement(range(n_o), d)))


def to_free(oct_):
    """Symmetric octant -> vector of free entries."""
    idx = free_index(oct_.shape[0], oct_.ndim)
    return oct_[tuple(idx.T)]


def from_free(v, n_o, d=3):
    """Vector of free entries -> symmetric octant."""
    idx = free_index(n_o, d)
    out = jnp.zeros((n_o,) * d, dtype=v.dtype)
    for p in itertools.permutations(range(d)):
        out = out.at[tuple(idx[:, list(p)].T)].set(v)
    return out
